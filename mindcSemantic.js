export class VariableLinker {
	/**
	 * 
	 * @param {string} variableName 
	 * @param {SymbolEntry} entry
	 */
	constructor(variableName, entry) {
		/**
		 * @type {VariableLinker[]}
		 */
		this.linked = [];
		/**
		 * @type {AttributeClass[]}
		 * 
		 * Nodes that prepare to delete something.
		 */
		this.prepared = [];
		/**
		 * @type {VariableLinker}
		 */
		this.parent = null;
		/**
		 * @type {string}
		 */
		this.name = variableName;
		this.rejecting = false;
		this.entry = entry;
	}

	/**
	 * 
	 * @param {VariableLinker} linker 
	 */
	linkTo(linker) {
		if (linker.rejecting) return;
		linker.linked.push(this);
		this.parent = linker;
	}

	invalidate() {
		this.parent = null;
		this.prepared.forEach(obj => void(obj.setAttribute('candidateRemoval', 0)));
		this.prepared = [];
	}

	unlink() {
		if (!this.parent) {
			return;
		}
		const index = this.parent.linked.indexOf(this);
		if (index != -1) {
			this.parent.linked.splice(index);
		}
		this.invalidate();
	}

	modify() {
		this.linked.forEach(obj => void(obj.invalidate()));
		this.linked = [];
		this.unlink();
	}

	/**
	 * 
	 * @returns {string}
	 */
	getName() {
		if (!this.parent) {
			return this.name;
		}
		return this.parent.getName();
	}

	/**
	 * 
	 * @param {AttributeClass} candidate 
	 */
	registerCandidate(candidate) {
		if (this.parent) {
			candidate.setAttribute('candidateRemoval', 2);
		} else {
			candidate.setAttribute('candidateRemoval', 0);
		}
		this.prepared.push(candidate);
	}
}

// 修改SymbolEntry类以存储更详细的类型信息
/**
 * @member {boolean} accessThroughPointer Indicating whether the variable should be accessed by a memory address (not necessarily be a pointer!)
 * @member {boolean} implementAsPointer Indicating whether the variable IS a pointer (or array, which is regarded as a pointer.)
 * @member {boolean} needMemoryAllocation
 */
export class SymbolEntry {
	/**
	 * 
	 * @param {string} name 
	 * @param {TypeInfo | string | {returnType: string, parameters: {name: string, type: string}[]}} type 
	 * @param {Scope | null} scope 
	 * @param {string} kind 
	 * @param {*} location 
	 * @param {number} size 
	 */
    constructor(name, type, scope, kind, location = null, size = null) {
        this.name = name;
        this.type = type; // 类型信息（现在是TypeInfo对象）
		this.size = size;	// Should be generated by compiler system
        this.scope = scope;
		this.owningScope = null;	// The scope that the function (if it points to one) owns
        this.kind = kind; // 'variable', 'function', 'parameter', 'type'
        this.location = location;
        this.initialized = false;
        this.used = false;
		// Unused:
		this.readCount = 0; // 读取次数
        this.writeCount = 0; // 写入次数
		// Unused end
	
		/**
		 * @type {MemoryBlockInfo?}
		 */
        this.memoryLocation = null;
		this.accessThroughPointer = false;	// In-memory variable, must be accessed through memory blocks
											// THIS ALSO MEANS THAT: you can and should always dereference it to get the real value
		this.implementAsPointer = (this.myType() instanceof TypeInfo && (this.myType().kind === 'pointer' || this.myType().kind === 'array'));
											// This is true will mean that when getting value, it will return a pointer
											// ACCORDING TO THAT DEFINITION, struct SHOULD BE "IMPLEMENTED AS POINTER"
											// instead of "ACCESS THROUGH POINTER"
		this.needMemoryAllocation = false;

		this.extraMemoryLocation = null;	// For variables having both access-through and implement-as, this will be the memory space where their value is placed.
		this.isExtraNear = false;			// This should be written by and only by code generator

		/**
		 * @type { {stackSymbols: SymbolEntry[], regStructMem: Map<string, string> }? }
		 */
		this.memberHandler = null;

		this.isAuto = false;
		this.isAutoDevice = false;	// Must be manually done!
		this.isVirtualSymbol = false;
		this.isRecursiveSymbol = false;
		// (for struct, union, pointer and array)

		// Following of these can be automatic sometimes
        this.isGlobal = false;
		this.isRegister = false; // 标记是否为register变量
		this.isStatic = (this.myType() instanceof TypeInfo) ? this.myType().isStatic() : false;
		this.isExtern = (this.myType() instanceof TypeInfo) ? this.myType().isExtern() : false;
		this.isRemote = (this.myType() instanceof TypeInfo) ? this.myType().isRemote() : false;
		// Note: this is also available for functions:
		// (for functions, once 'true', it can't be inlined !)
        this.isAddressed = false; // 标记是否被取地址
		this.isConst = (this.myType() instanceof TypeInfo) ? this.myType().isConst() : false;
        this.isVolatile = (this.myType() instanceof TypeInfo) ? this.myType().isVolatile() : false;
		// 常量传播相关
        this.isConstant = false;
        this.constantValue = null;

		// Used for code generator
		this.isNearPointer = false;

		// Simple array means array satisfying the following conditions that can be converted into a
		// builtin array by default:
		// 1. The array is of simple object type (Note: in this case, device, content_t and null_t are also allowed)
		// volatile variables, struct/union, array and pointer are NOT simple object types.
		// 2. The array is never cast to pointer type (Note: function calls permitted.)
		// If an array is both simple array and constant array, further optimization can be done.
		// If the array is of device, content_t (or sometimes null_t) type, then simple array is A MUST.
		/**
		 * If the type is 'embedded', it works like pdlist / sdlist. If it requires shared feature (i.e. remote access),
		 * instead of using 'sdlist' there will be an additional library not working in the same way as this array
		 * as the method must be specified.
		 * 
		 * By using array_init(type, mutable, implement, {data...}) you are also allowed to manually specify the way 
		 * such thing is loaded.
		 * 
		 * @type {arrayStyle}
		 */
		this.arrayStyle = {
			type: 'traditional',
			mutable: true,
			implement: null
		};
        
        // 优化标记 [Not really used right away]
        this.canBeEliminated = false;
        this.isDead = false;

		// Optimizer tag used now
		this.variableReferrer = new VariableLinker(name, this);
    }
	
	// 标记为常量
    markAsConstant(value) {
        this.isConstant = true;
        this.constantValue = value;
		/*

		let typeRef = this.myType();
        if (typeRef && typeRef.qualifiers) {
            typeRef.qualifiers.push('const');
        }
			*/
    }

	/**
	 * 
	 * @returns {TypeInfo | null | {returnType: string; parameters: any[]}}
	 * @deprecated Use it only when you don't care about memory attributes.
	 */
	myType() {
		if (!this.type) return null;
		return this.type.type ? this.type.type : this.type;
	}

	isStructOrUnion() {
		if (!this.type) return false;
		const curType = this.myType();
		return curType.kind === 'struct' || curType.kind === 'union';
	}

	isBasic() {
		const curType = this.myType();
		return curType && curType.kind === 'basic';
	}

	isPointer() {
		return this.accessThroughPointer || this.implementAsPointer || this.needMemoryAllocation;
	}

	/**
	 * 
	 * @returns {boolean}
	 */
	requireExtraMemory() {
		return this.accessThroughPointer && this.myType().isTypeInfo && ['array', 'struct', 'union'].includes(this.myType().kind);
	}

	memoryRef() {
		return this.requireExtraMemory() ? this.extraMemoryLocation : this.memoryLocation;
	}

	/**
	 * In current version, a structure can't be regarded as `accessThroughPointer`.
	 * @returns {boolean}
	 */
	isRegistryStruct() {
		return this.isStructOrUnion() && !this.isPointer();
	}

	getAssemblySymbol() {
		if (this.isAutoDevice) {
			return this.name;
		}
		if (this.kind === 'function') {
			return '_' + this.name;
		}
		if (this.scope) {
			return this.scope.getPath() + "." + this.name;
		} else {
			return this.name;
		}
	}

	duplicate() {
		let result = new SymbolEntry(this.name, this.type, this.scope, this.kind);
		Object.assign(result, this);
		return result;
	}

	/**
	 * 
	 * @returns {TypeInfo}
	 * @throws
	 */
	extractType() {
		/**
		 * @type {TypeInfo}
		 */
		let resultType;
		if (this.kind !== 'function') {
			// Let it crash otherwise.
			resultType = this.myType().duplicate();
			// if (resultType.isTypeInfo) {
			/*
			Every conversion of the type used to push these again, so a type
			touched more than once ended up with `const const const`. Add each
			qualifier at most once.
			*/
			const withQualifier = name => {
				if (!resultType.qualifiers.includes(name)) resultType.qualifiers.push(name);
			};
			if (this.isAuto || this.isAutoDevice) withQualifier('auto');
			if (this.isRegister) withQualifier('register');
			if (this.isConst || resultType.isConst()) withQualifier('const');
			if (this.isVolatile || resultType.isVolatile()) withQualifier('volatile');
			if (this.isExtern) withQualifier('extern');
			if (this.isStatic) withQualifier('static');
			resultType.qualifiers = [...new Set(resultType.qualifiers)];
			// }	// I guess it should crash otherwise. If there's no judgment, it will
		} else {
			resultType = new TypeInfo(this.name, 'function', 1);
			resultType.functionTo = this;
		}
		return resultType;
	}

	isArray() {
		return this.extractType().kind === 'array';
	}

	describe() {
		return `${this.name}: ${
			(typeof this.type === 'object') ? this.extractType().toString() : `#${this.type}`} @ ${this.scope ? this.scope.getPath() : 'g'}`;
	}

	/**
	 * 
	 * @param {Scope} scope 
	 */
	belongingTo(scope) {
		/**
		 * 
		 * @param {Scope} s
		 * @returns {boolean}
		 */
		let checkScope = s => (s ? (s == scope || checkScope(s.parent)) : false);
		return checkScope(this.scope);
	}

	/**
	 * @returns {string?}
	 */
	getFunctionRegion() {
		const search = scope => {
			if (!scope) return null;
			if (scope.type === 'f') return scope.astNode ? scope.astNode.name : null;
			if (!scope.parent) return null;
			return search(scope.parent);
		};
		return this.scope ? search(this.scope) : null;
	}
}

// 作用域类
export class Scope {
    constructor(parent = null, type = 'b', astNode = null, name = '') {
        this.parent = parent;
		/**
		 * @type {'g' | 'f' | 'b' | 'l'}
		 */
        this.type = type; // g 'global', f 'function', b 'block', l 'inline'
		this.name = name;
		/**
		 * @type {ASTNode}
		 */
		this.astNode = astNode; // 关联的AST节点
		/**
		 * @type {Map<string, SymbolEntry>}
		 */
        this.symbols = new Map();
		/**
		 * @type {Scope[]}
		 */
        this.children = [];
		
		if (parent) {
            parent.children.push(this);
        }
    }

    addSymbol(symbol) {
        this.symbols.set(symbol.name, symbol);
		symbol.scope = this; // 建立双向关联
    }
	
	removeSymbol(name) {
		this.symbols.delete(name);
	}

	/**
	 * 
	 * @param {string} name 
	 * @returns {SymbolEntry | null}
	 */
    lookup(name) {
        return this.symbols.get(name) || (this.parent ? this.parent.lookup(name) : null);
    }
	
	/**
	 * 
	 * @param {string} name 
	 * @returns {Scope | null}
	 */
	lookupScopeOf(name) {
		if (this.symbols.has(name)) {
			return this;
		}
		const result = this.parent ? this.parent.lookupScopeOf(name) : null;
		return result;
	}

    lookupCurrent(name) {
        return this.symbols.get(name) || null;
    }
	
	// 获取当前作用域的所有符号
	/**
	 * @returns {SymbolEntry[]} All symbols of current scope.
	 * @remark Notice: children scopes' information isn't included.
	 */
    getAllSymbols() {
        return Array.from(this.symbols.values());
    }

	/**
	 * @returns {SymbolEntry[]}
	 */
	recursivelyGetAllSymbols() {
		return [...this.getAllSymbols(), ...(this.children.flatMap(child => child.recursivelyGetAllSymbols())) ];
	}
	
	// 获取作用域的完整路径
    getPath() {
        const path = [];
        let current = this;
        while (current) {
            path.unshift(current.type + ':' + current.name);
            current = current.parent;
        }
        return path.join('.');
    }

	// Shallow duplicate
	duplicate() {
		const scope = new Scope(this.parent, this.type, this.astNode, this.name);
		scope.children = [...this.children];
		scope.symbols = new Map([...this.symbols].map(([key, symb]) => {
			const dup = symb.duplicate();
			dup.scope = scope;
			return [key, dup];
		}));
		scope.duplicateIdent = (this.duplicateIdent ?? 0) + 1;
		return scope;
	}

	duplicateAll() {
		const scope = new Scope(this.parent, this.type, this.astNode, this.name);
		scope.children = this.children.map(child => child.duplicateAll());
		scope.children.forEach(child => {
			child.parent = scope;
		});
		scope.symbols = new Map([...this.symbols].map(([key, symb]) => {
			const dup = symb.duplicate();
			dup.scope = scope;
			return [key, dup];
		}));
		scope.fullDuplicateIdent = (this.fullDuplicateIdent ?? 0) + 1;
		return scope;
	}

	/**
	 * 
	 * @param {Scope} scope 
	 * @returns {boolean} Returns whether the given scope is a parent of current scope.
	 */
	isParent(scope) {
		if (!scope) return false;
		if (scope === this) return true;
		if (!this.parent) return false;
		return this.parent.isParent(scope);
	}
}

// 首先，添加一些辅助类
export class TypeInfo {
	/**
	 * 
	 * @param {string} name 
	 * @param {string} kind 
	 * @param {number} size 
	 * @param {MemberInfo[] | null} members 
	 */
    constructor(name, kind, size = 1, members = null) {
        this.name = name; // 类型名称
        this.kind = kind; // 'basic', 'struct', 'union', 'pointer', 'array', 'function', 'device', 'null'
        this.size = size; // 类型大小（按1字节对齐）
		/**
		 * @type {MemberInfo[]}
		 */
        this.members = members ?? []; // 结构体/联合体成员
        this.pointerTo = null; // 对于指针类型，指向的类型 (MUST BE A TYPE, NOT A FUNCTION)
        this.arraySize = null; // 对于数组类型，数组大小
        this.qualifiers = []; // 类型限定符: const, volatile, auto, register, extern, etc.
		// Probably we consider 'near' and 'far' as well
		this.functionTo = null;	// Pointing to what function for function type
		this.memberReference = null;
		/**
		 * @type {true}
		 */
		this.isTypeInfo = true;

		this.annotations = new AttributeClass();
    }
    
    isConst() {
        return this.qualifiers.includes('const');
    }
    
    isVolatile() {
        return this.qualifiers.includes('volatile');
    }

	/**
	 * Whether the value lives in ANOTHER processor: every access becomes a
	 * `read` / `write` on the device named by the pointer.
	 *
	 * @returns {boolean}
	 */
	isRemote() {
		return (this.qualifiers ?? []).includes('remote');
	}

	isExtern() {
		return this.qualifiers.includes('extern');
	}

	isStatic() {
		return this.qualifiers.includes('static');
	}

	isNear() {
		return this.qualifiers.includes('near');
	}

	/**
	 * Discard qualifiers.
	 * @param {string[]} qualifiers 
	 * @returns {TypeInfo}
	 */
	discardQualifier(qualifiers) {
		let result = new TypeInfo(this.name, this.kind, this.size, this.members);
		Object.assign(result, this);
		result.qualifiers = result.qualifiers.filter(q => (!qualifiers.includes(q)));
		return result;
	}

	/**
	 * 
	 * @returns {boolean}
	 */
	/**
	 * Whether the DEFINITION itself forces this struct into memory, i.e. whether
	 * it embeds something that needs memory (an array, or a struct that needs
	 * memory) at any depth. This is a property of the type, so every instance of
	 * it must be stored in memory -- no copy can stay in registers.
	 *
	 * @param {Set<string>} [seen] Guard against recursive definitions
	 * @returns {boolean}
	 */
	intrinsicallyRequiresMemory(seen = null) {
		if (!['struct', 'union'].includes(this.kind)) return false;
		const visited = seen ?? new Set();
		if (this.name) {
			if (visited.has(this.name)) return false;
			visited.add(this.name);
		}
		return (this.members ?? []).some(member =>
			member && member.type && member.type.isTypeInfo && member.type.isRequireMem());
	}

	isStrictPointerImpl() {
		const pointerImplementation = ['pointer', 'array'];
		if (this.kind === 'struct' || this.kind === 'union') {
			/*
			`forceMemoryImpl` is set on a COPY of the type when an instance of it
			has its address taken. A processor has no way to point at a group of
			registers, so that copy has to become a piece of memory. Instances
			whose address is never taken keep the original type and stay in
			registers.
			*/
			if (this.forceMemoryImpl === true) return true;
			/*
			A struct that CONTAINS an array -- or a struct that itself must live in
			memory -- can never be held in registers either: the array needs memory
			of its own, and how many of them a running program needs is not known
			at compile time (a recursive call may need arbitrarily many).
			*/
			return (this.members ?? []).some(member =>
				member && member.type && member.type.isTypeInfo && member.type.isRequireMem());
		}
		return ((typeof this.kind === 'object') && this.kind.isStrictPointerImpl()) ||
		 pointerImplementation.includes(this.kind);
	}


	/**
	 * 
	 * @returns {boolean}
	 */
	isPointerImpl() {
		const pointerImplementation = ['pointer', 'array'];
		if (this.kind === 'struct' || this.kind === 'union') {
			return this.isVolatile() || this.isStrictPointerImpl();
		}
		return ((typeof this.kind === 'object') && this.kind.isPointerImpl()) ||
		 pointerImplementation.includes(this.kind) || this.isVolatile();
	}

	/**
	 * The difference between this and isPointerImpl() is that simple pointer might not require
	 * memory assignment.
	 * 
	 * @returns {boolean}
	 */
	isRequireMem() {
		const pointerImplementation = ['array'];
		if (this.kind === 'struct' || this.kind === 'union') {
			return this.isVolatile() || this.isStrictPointerImpl();
		}
		return ((typeof this.kind === 'object') && this.kind.isPointerImpl()) ||
		 pointerImplementation.includes(this.kind) || this.isVolatile();
	}

	isRegStruct() {
		return (this.kind === 'struct' || this.kind === 'union') && !this.isPointerImpl();
	}

	initializeReferenceTable() {
		this.memberReference = new Map();	// Used only in generation
		this.members.forEach(member => {
			this.memberReference.set(member.name, member.offset);
		});
	}	
    
    toString() {
		/*
		Qualifiers accumulate while a type is copied around, so print each one
		once. The pointee is printed WITHOUT re-listing the outer qualifiers and
		the `*` goes where C puts it, otherwise `const int *` came out as
		`const const const int*`.
		*/
		/*
		A qualifier describes the level it sits on, and for a POINTER the levels
		are genuinely different types: `const int *` is a pointer to a constant
		int, `int *const` is a constant pointer to a plain int. So every level
		prints its OWN qualifiers and `const int *const` keeps both -- the
		pointer's own ones go after the `*`, the way C writes them.

		Duplicates are still dropped, but only WITHIN one level: they come from
		the same type being copied around and say nothing.
		*/
		const qualifiersOf = t => [...new Set(t?.qualifiers ?? [])];
		const render = t => {
			if (!t) return '';
			const own = qualifiersOf(t);
			if ((t.kind === 'pointer' || t.kind === 'array') && t.pointerTo) {
				const inner = render(t.pointerTo);
				if (t.kind === 'pointer') {
					return inner + '*' + (own.length > 0 ? ' ' + own.join(' ') : '');
				}
				/*
				An array has no separate surface syntax -- C writes
				`const int[5]`, never `int[5] const` -- so the element level
				carries the qualifier and the array level only adds what the
				element does not already show.
				*/
				const extra = own.filter(q => !qualifiersOf(t.pointerTo).includes(q));
				/*
				`arraySize` is not necessarily a number: it is often the
				literal NODE from the declarator. Interpolating it straight
				into a template calls its `toString()`, which reaches for a
				source location and throws.
				*/
				const sizeOf = x => {
					if (x === undefined || x === null) return '';
					if (typeof x === 'string' || typeof x === 'number') return String(x);
					if (Array.isArray(x)) return x.map(sizeOf).join('');
					return String(x.value ?? '');
				};
				return (extra.length > 0 ? extra.join(' ') + ' ' : '') + inner
					+ `[${sizeOf(t.arraySize)}]`;
			}
			// `name` may be a node rather than a string in odd cases
			const name = (typeof t.name === 'string') ? t.name : (t.name?.value ?? '');
			return (own.length > 0 ? own.join(' ') + ' ' : '') + name;
		};
		let result = render(this);
		if (this.kind === 'function') {
			if (this.functionTo) {
				result += '{' + this.functionTo.type.returnType.toString() + ' || ';
				result += (this.functionTo.type.parameters.map(param => (param.type.toString()))).join(',') + '}';
			} else {
				result = `{ ??${this.name} }`;
			}
		}
        return result;
    }

	/**
	 * Return the result of single-layer dereference (through * or [])
	 * @returns {TypeInfo}
	 */
	extractSingle() {
		if (this.kind === 'array') {
			if (!this.pointerTo) return null;
			/**
			 * @type {TypeInfo}
			 */
			const tmpl = this.duplicate();
			if (this.arraySize.length > 1) {
				tmpl.size = tmpl.size / this.arraySize[0];
				tmpl.arraySize = this.arraySize.slice(1);
				return tmpl;
			} else {
				return this.pointerTo;
			}
		} else {
			return this.pointerTo;
		}
	}

	/**
	 * 
	 * @param {number} k 
	 * @returns {TypeInfo?}
	 */
	extractKth(k) {
		if (['array', 'pointer'].includes(this.kind)) {
			return this.extractSingle();
		} else if (['struct', 'union'].includes(this.kind)) {
			return this.members[k];
		} else {
			return null;
		}
	}

	/**
	 * @remark Shallow copy for members and comprehensive copy for qualifiers.
	 * @returns {TypeInfo}
	 */
	duplicate() {
		let result = new TypeInfo(this.name, this.kind, this.size);
		Object.assign(result, this);
		result.qualifiers = [...new Set(this.qualifiers)];
		return result;
	}
}

